def main() -> None:
    seed = []
    eval_in = []
    review = ["# 챗봇 FAQ 초안 검토표", "",
              "자동 생성 파일입니다(`scripts/chatbot/build_seed.py`). 답변은 **초안**이며, 정책 설명이 틀리면 챗봇이 틀린 답을 합니다. "
              "아래 '확인 필요'를 먼저 봐 주세요.", "",
              "| # | 분류 | seedKey | 대표 질문 | 근거(코드/설정) | 확인 필요 |", "|---|---|---|---|---|---|"]
    for i, (key, cat, qs, ans, src, evals, note) in enumerate(FAQS, 1):
        seed.append({"seedKey": key, "category": cat, "answer": ans, "enabled": True, "questions": qs})
        for q in evals:
            eval_in.append({"expected": key, "question": q})
        review.append(f"| {i} | {cat} | `{key}` | {qs[0]} | {src} | {note or '-'} |")
    review += ["", "## 답변 전문", ""]
    for key, cat, qs, ans, *_ in FAQS:
        review += [f"### {qs[0]} (`{key}`, {cat})", "", ans, ""]
    (ROOT / "src/main/resources/chatbot").mkdir(parents=True, exist_ok=True)
    (ROOT / "src/test/resources/chatbot").mkdir(parents=True, exist_ok=True)
    (ROOT / "src/main/resources/chatbot/faq-seed.json").write_text(
        json.dumps(seed, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    (ROOT / "src/test/resources/chatbot/eval-set.json").write_text(
        json.dumps({"inScope": eval_in, "outOfScope": OUT_OF_SCOPE}, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    (ROOT / "docs/chatbot/FAQ_REVIEW.md").write_text("\n".join(review) + "\n", encoding="utf-8")
    print(f"FAQ {len(seed)}건, 평가 질문 {len(eval_in)}건(범위 안) + {len(OUT_OF_SCOPE)}건(범위 밖)")


if __name__ == "__main__":
    main()
